//! A reusable single-line text input entity. GPUI has no built-in text field
//! (pre-1.0, see CLAUDE.md GPUI guidelines), so this adapts the pattern from
//! gpui's own `examples/input.rs` (pinned rev) into a themed component other
//! views can embed.

use std::ops::Range;

use gpui::{
    actions, div, fill, point, prelude::*, px, relative, size, App, Bounds, ClipboardItem, Context,
    CursorStyle, ElementId, ElementInputHandler, Entity, EntityInputHandler, FocusHandle,
    Focusable, GlobalElementId, KeyBinding, LayoutId, MouseButton, MouseDownEvent, MouseMoveEvent,
    MouseUpEvent, PaintQuad, Pixels, Point, ShapedLine, SharedString, Style, TextRun,
    UTF16Selection, UnderlineStyle, Window,
};
use unicode_segmentation::UnicodeSegmentation;

use crate::theme::GlassTheme;

pub type ConfirmHandler = Box<dyn Fn(&str, &mut Window, &mut Context<TextInput>)>;
pub type CancelHandler = Box<dyn Fn(&mut Window, &mut Context<TextInput>)>;

